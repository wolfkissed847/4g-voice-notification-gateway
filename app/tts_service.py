"""
TTS Service — แปลงข้อความภาษาไทยเป็นไฟล์เสียงด้วย gTTS

ไม่ cache ไฟล์เสียงไว้ใช้ซ้ำ — แปลงใหม่ทุกครั้งที่จะโทร (ตัดสินใจ 6 ส.ค. 2569 หลังวัดเวลาจริงแล้ว
gTTS ใช้เวลาแค่ ~0.3-0.9 วิ ต่อข้อความ เทียบกับเวลาอัปโหลดไฟล์เสียงเข้าโมดูล GSM ที่กินเวลา
เป็นสิบวิ (ดู gsm_module.py) ส่วนต่างนี้ผู้ใช้ไม่รู้สึกเลย จึงไม่คุ้มความซับซ้อนของการทำ cache
ดู LIMITATIONS.md ข้อ 1 สำหรับผลที่ตามมา: ถ้าอินเทอร์เน็ตล่มตอนจะโทร จะสร้างเสียงไม่ได้เสมอ
(ไม่ใช่แค่ตอนข้อความยังไม่เคยสร้าง เหมือนตอนที่ยังมี cache)

ใช้ชื่อไฟล์คงที่ ไม่ใช่ hash ต่อข้อความ — เพราะ worker ประมวลผลทีละ job เดียว (ซิมใบเดียว
โทรได้ทีละสาย ดู LIMITATIONS.md ข้อ 2) จึงไม่มีโอกาสสองสายเขียนทับกันพร้อมกัน และ
ไฟล์เก่าที่ไม่ได้ใช้ต่อจะไม่ค้างสะสมในดิสก์เหมือนตอนที่ยัง cache ด้วย hash
"""
import logging
import os
import shutil
import subprocess

from gtts import gTTS

from app.config import settings

logger = logging.getLogger("tts_service")

_OUTPUT_FILENAME = "notify.mp3"
_RAW_FILENAME = "notify_raw.mp3"

# บีบไฟล์เสียงก่อนอัปเข้าโมดูลด้วย sox — วัดกับ A7670E จริง 22 ก.ย. 2569:
# gTTS ส่งมาที่ 24kbps/24kHz ได้ไฟล์ ~71KB ต่อข้อความ 9 วินาที ซึ่งใหญ่เกินจำเป็นมาก
# เพราะสายโทรศัพท์ตัดความถี่เหลือ 8kHz อยู่แล้ว ปลายสายจึงไม่ได้ยินส่วนที่เกินนั้นเลย
# 8kbps/8kHz mono เหลือ ~9KB (เล็กลง 8 เท่า) เสียงที่ปลายสายได้ยินเหมือนเดิม
#
# ทำไมไม่ใช้ AMR-NB ทั้งที่เป็นโคเดกของโทรศัพท์โดยตรงและคู่มือบอกว่ารองรับ:
# ทดสอบแล้วโมดูล "รับไฟล์ครบและตอบ OK ทุกขั้น" แต่ตอนเล่นจริงได้แค่ 0.24 วิ
# จากเสียงยาว 8.93 วิ — คือเงียบทั้งสาย โดยไม่มี error ให้จับได้เลยสักจุด
# (ลองทั้ง 12.2kbps และ default 4.75kbps ผลเหมือนกัน) ห้ามเปลี่ยนกลับไปใช้ .amr
# นอกจากจะทดสอบการเล่นจริงกับฮาร์ดแวร์แล้วว่าความยาวตรงกับไฟล์ต้นทาง
_TARGET_RATE = "8000"

# ⚠️ เพดานแข็งของโมดูล: AT+CFTRANRX รับไฟล์ได้ไม่เกิน 20,480 ไบต์ (20KB) พอดี
# วัดจริง 22 ก.ย. 2569 ด้วยการไล่ขนาดทีละไบต์: 20,480 = OK / 20,481 = ERROR
# ทดสอบสลับไปมาหลายรอบได้ผลเดิมทุกครั้ง ไม่ใช่สถานะค้างจากรอบก่อน
#
# เกินเพดานแล้วโมดูลตอบ ERROR ทันที = อัปโหลดไม่สำเร็จ = โทรไม่ได้ทั้งสาย
# (ไม่ใช่แค่เสียงแย่ลง) ข้อความยาว 500 ตัวอักษรซึ่งเป็นเพดานที่ระบบยอมรับ
# ได้เสียงยาว ~65 วินาที = ~65KB ที่ 8kbps ซึ่งเกินเพดานนี้ไป 3 เท่า
_MODULE_MAX_BYTES = 20480

# ไล่จากคุณภาพดีสุดลงมา — ใช้ตัวแรกที่ไฟล์ไม่เกินเพดานโมดูล
#
# ทำไมไม่ fix ที่ 8kbps ตัวเดียวเหมือนเดิม: 8kbps เสียงเพี้ยนจากต้นฉบับ 15.5%
# (วัดด้วยการลบสัญญาณเทียบกับ 32kbps) ผู้ใช้รายงานว่า "ฟังเหมือนขาดๆ หายๆ
# เวลาพูดยาวๆ แต่ยังฟังออก" ซึ่งตรงกับตัวเลขนี้ — 16kbps ลดความเพี้ยนเหลือ 9.7%
#
# ข้อความสั้น (ส่วนใหญ่ของงานจริง) จึงได้ 16kbps ที่ฟังชัดกว่า
# ส่วนข้อความยาวที่ 16kbps แล้วเกิน 20KB จะถอยลงมา 8kbps ให้ยังโทรออกได้
# — เสียงแย่ลงดีกว่าโทรไม่ออกเลย
_BITRATE_LADDER = ["16", "8"]


def _compress_for_module(src: str, dst: str) -> bool:
    """บีบ mp3 ให้เล็กลงด้วย sox คืน True ถ้าสำเร็จ

    ไม่มี sox ในเครื่อง = ไม่ใช่เหตุให้โทรไม่ออก แค่กลับไปใช้ไฟล์เดิมที่ใหญ่กว่า
    (ช้าลงแต่ยังทำงานได้) จึงจับ exception ทั้งหมดแล้วคืน False แทนที่จะโยนต่อ
    """
    if not shutil.which("sox"):
        logger.warning("ไม่พบ sox — ใช้ไฟล์เสียงขนาดเต็มแทน อัปโหลดเข้าโมดูลจะช้ากว่าปกติ")
        return False

    for bitrate in _BITRATE_LADDER:
        try:
            subprocess.run(
                ["sox", src, "-r", _TARGET_RATE, "-c", "1", "-C", bitrate, dst],
                check=True,
                capture_output=True,
                timeout=30,
            )
        except (subprocess.SubprocessError, OSError) as exc:
            logger.warning("บีบไฟล์เสียงไม่สำเร็จ ใช้ไฟล์ขนาดเต็มแทน: %s", exc)
            return False
        # sox จบด้วย exit 0 แต่ได้ไฟล์เปล่าถือว่าล้มเหลว — ปล่อยไปจะกลายเป็นสายเงียบ
        if not os.path.exists(dst) or os.path.getsize(dst) == 0:
            logger.warning("sox คืนไฟล์เปล่า ใช้ไฟล์ขนาดเต็มแทน")
            return False

        size = os.path.getsize(dst)
        if size <= _MODULE_MAX_BYTES:
            logger.info("บีบเสียงที่ %s kbps ได้ %d ไบต์ (เพดานโมดูล %d)", bitrate, size, _MODULE_MAX_BYTES)
            return True
        logger.info("ที่ %s kbps ได้ %d ไบต์ เกินเพดานโมดูล — ลองบิตเรตต่ำลง", bitrate, size)

    # ต่ำสุดแล้วยังเกินเพดาน = ข้อความยาวเกินกว่าที่โมดูลจะรับไหว
    # ปล่อยผ่านไปให้ _upload_file ตอบ ERROR เองจะงงกว่า จึงเตือนให้ชัดตั้งแต่ตรงนี้
    logger.error(
        "ไฟล์เสียงยังใหญ่เกินเพดานโมดูล (%d ไบต์ > %d) แม้บีบต่ำสุดแล้ว — "
        "ข้อความยาวเกินไป อัปโหลดเข้าโมดูลจะไม่สำเร็จ ควรลดความยาวข้อความลง",
        os.path.getsize(dst),
        _MODULE_MAX_BYTES,
    )
    return True
    return True


def _add_pauses(text: str) -> str:
    """แทนช่องว่างด้วยจุลภาค เพื่อให้เสียงพูดเว้นวรรคจริง

    ภาษาไทยเขียนติดกันไม่เว้นวรรคระหว่างคำ ช่องว่างจึงทำหน้าที่เหมือนเครื่องหมายวรรคตอน
    ของภาษาอื่น แต่เสียงอ่านของ Google ไม่ได้ตีความแบบนั้น — มันอ่านรวดเดียวจนคำท้ายวรรค
    กับคำต้นวรรคถัดไปเกยกัน ทำให้ฟังเหมือนคำหายไปทั้งคำ

    เจอจากการใช้จริง 22 ก.ย. 2569: "แจ้งเตือน เชื่อมต่ออินเทอร์เน็ตไม่ได้ กรุณาตรวจสอบ"
    ฟังแล้วได้ยินเป็น "แจ้งเตือนอินเทอร์เน็ตไม่ได้กรุณาตรวจสอบ" — คำว่า "เชื่อมต่อ" หายไป
    เพราะถูกกลืนเข้ากับ "เตือน" ที่อยู่ติดกัน

    วัดจริงกับข้อความเดียวกัน: ใช้ช่องว่างได้ช่วงเงียบรวม 0.68 วิ / ใช้จุลภาคได้ 1.16 วิ
    (ขึ้นบรรทัดใหม่ไม่ช่วยเลย ได้ 0.68 วิ เท่าช่องว่าง) เสียงยาวขึ้น ~1.25 วิ ซึ่งแลกได้
    เพราะข้อความแจ้งเตือนต้องฟังรู้เรื่องตั้งแต่ครั้งแรก ไม่มีโอกาสให้ฟังซ้ำ

    ไม่เติมถ้ามีจุลภาค/มหัพภาคอยู่แล้ว — ผู้ใช้ตั้งใจวางเองก็เคารพตามนั้น
    """
    if "," in text or "." in text:
        return text
    parts = [p for p in text.split() if p]
    return ", ".join(parts) if len(parts) > 1 else text


def text_to_speech(text: str) -> str:
    """แปลงข้อความเป็นไฟล์เสียง mp3 แล้วคืน path ของไฟล์ — สร้างใหม่ทับไฟล์เดิมทุกครั้ง"""
    os.makedirs(settings.audio_cache_dir, exist_ok=True)
    file_path = os.path.join(settings.audio_cache_dir, _OUTPUT_FILENAME)
    raw_path = os.path.join(settings.audio_cache_dir, _RAW_FILENAME)

    spoken = _add_pauses(text)
    if spoken != text:
        logger.info("เติมจังหวะเว้นวรรคให้เสียงพูด: %r", spoken)

    tts = gTTS(text=spoken, lang=settings.tts_language)
    tts.save(raw_path)

    if _compress_for_module(raw_path, file_path):
        logger.info(
            "สร้างไฟล์เสียง: %s (%d ไบต์ จากต้นฉบับ %d ไบต์)",
            file_path,
            os.path.getsize(file_path),
            os.path.getsize(raw_path),
        )
    else:
        shutil.copyfile(raw_path, file_path)
        logger.info("สร้างไฟล์เสียง: %s (%d ไบต์ ไม่ได้บีบ)", file_path, os.path.getsize(file_path))
    return file_path
