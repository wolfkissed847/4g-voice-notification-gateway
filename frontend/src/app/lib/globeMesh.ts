/** ระบบพิกัดของ SVG: viewBox 0 0 220 220 ศูนย์กลางลูกโลกที่ (110,110) */
const CX = 110;
const CY = 110;
/** รัศมีผิวลูกโลก */
const R = 82;
/** รัศมีของโครงข่ายที่ล้อมอยู่ — เกินผิวลูกโลกออกมา เหมือนในภาพอ้างอิง */
const R_MESH = 101;

/** เอียงแกนขึ้นเล็กน้อย ขั้วโลกจะได้ไม่อยู่กลางภาพพอดีจนดูเป็นวงกลมสมมาตรเกินไป */
const TILT = -0.34; // เรเดียน

export type Pt = { x: number; y: number; z: number };

/**
 * กระจายจุดบนทรงกลมด้วย Fibonacci lattice แล้วฉายลงระนาบ
 * z > 0 = อยู่ด้านหน้า (หันเข้าหาคนดู), z < 0 = อยู่ด้านหลังลูกโลก
 */
function sphere(count: number, radius: number): Pt[] {
  const golden = Math.PI * (3 - Math.sqrt(5));
  const out: Pt[] = [];
  for (let i = 0; i < count; i++) {
    const yUnit = 1 - (i / (count - 1)) * 2;
    const ring = Math.sqrt(Math.max(1 - yUnit * yUnit, 0));
    const theta = golden * i;
    const x0 = Math.cos(theta) * ring;
    const y0 = yUnit;
    const z0 = Math.sin(theta) * ring;
    // เอียงรอบแกน X
    const y1 = y0 * Math.cos(TILT) - z0 * Math.sin(TILT);
    const z1 = y0 * Math.sin(TILT) + z0 * Math.cos(TILT);
    out.push({ x: CX + x0 * radius, y: CY - y1 * radius, z: z1 });
  }
  return out;
}

/** จุดบนผิวลูกโลก — เอาเฉพาะซีกหน้า ซีกหลังถูกตัวลูกโลกบังอยู่แล้ว */
export const SURFACE_DOTS: Pt[] = sphere(300, R).filter((p) => p.z > -0.08);

/** โหนดของโครงข่ายที่ล้อมลูกโลก */
export const MESH_NODES: Pt[] = sphere(78, R_MESH);

/**
 * เส้นเชื่อมระหว่างโหนดที่อยู่ใกล้กันพอ — ได้รูปสามเหลี่ยมย่อยๆ แบบในภาพอ้างอิง
 * เกณฑ์เป็นระยะบนระนาบภาพ ไม่ใช่ระยะ 3 มิติ เพราะสิ่งที่ต้องดูดีคือภาพที่ฉายออกมา
 * (ระยะ 3 มิติจะทำให้ขอบซ้าย-ขวาซึ่งโค้งหนีไปมีเส้นหนาแน่นผิดปกติ)
 */
export const MESH_EDGES: { x1: number; y1: number; x2: number; y2: number; z: number }[] = (() => {
  const out: { x1: number; y1: number; x2: number; y2: number; z: number }[] = [];
  const MAX = 46;
  for (let i = 0; i < MESH_NODES.length; i++) {
    for (let j = i + 1; j < MESH_NODES.length; j++) {
      const a = MESH_NODES[i];
      const b = MESH_NODES[j];
      const d = Math.hypot(a.x - b.x, a.y - b.y);
      if (d > MAX) continue;
      // เส้นที่ปลายทั้งสองอยู่หลังลูกโลกทั้งคู่ ถูกบังหมด ไม่ต้องวาด
      if (a.z < -0.35 && b.z < -0.35) continue;
      out.push({ x1: a.x, y1: a.y, x2: b.x, y2: b.y, z: (a.z + b.z) / 2 });
    }
  }
  return out;
})();
