/**
 * แปลงรหัสเครือข่ายตัวเลข (MCC+MNC) เป็นชื่อผู้ให้บริการที่คนอ่านรู้เรื่อง
 *
 * ปกติ backend สั่ง `AT+COPS=3,0` ตอนเชื่อมต่อโมดูลอยู่แล้ว เพื่อให้เครือข่ายส่ง "ชื่อ" มาตรงๆ
 * (ดู app/gsm_module.py connect()) ไฟล์นี้จึงเป็นแค่**ตัวสำรอง**สำหรับกรณีที่โมดูลยังตอบ
 * เป็นรหัสตัวเลขอยู่ เช่น ซิมบางค่ายที่ไม่มีชื่อฝังใน NVM ของโมดูล
 *
 * รหัส = MCC (3 หลักแรก = ประเทศ) + MNC (2-3 หลักหลัง = ค่าย)
 * 520 = ประเทศไทย
 *
 * เก็บเฉพาะรหัสที่ใช้จริงในไทยและมั่นใจว่าถูกต้อง — รหัสที่ไม่รู้จักจะคืนค่าเดิมไปแสดง
 * ไม่เดาชื่อมั่ว เพราะแสดงชื่อค่ายผิดแย่กว่าแสดงเป็นตัวเลขที่ผู้ใช้เอาไปค้นต่อได้
 */
const TH_OPERATORS: Record<string, string> = {
  '52000': 'TrueMove H',
  '52001': 'AIS',
  '52003': 'AIS',
  '52004': 'TrueMove H',
  '52005': 'dtac',
  '52015': 'NT (TOT)',
  '52018': 'dtac',
  '52020': 'TrueMove H',
  '52047': 'NT (CAT)',
};

/**
 * คืนชื่อที่เหมาะจะเอาไปแสดง
 * - ถ้าเป็นรหัสตัวเลขที่รู้จัก → คืนชื่อค่าย
 * - ถ้าเป็นชื่ออยู่แล้ว (โมดูลตอบมาเป็นชื่อ) → คืนตามเดิม
 * - ถ้าเป็นรหัสที่ไม่รู้จัก → คืนตามเดิม ไม่เดา
 */
export function operatorName(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const trimmed = raw.trim();
  return TH_OPERATORS[trimmed] ?? trimmed;
}
