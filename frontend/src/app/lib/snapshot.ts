/**
 * snapshot — เก็บข้อมูลที่หน้าโหลดมาแล้วไว้ในหน่วยความจำ เพื่อให้กลับเข้าหน้าเดิมแล้ว
 * เห็นของทันที ไม่ต้องรอโหลดใหม่ทุกครั้ง
 *
 * ── ปัญหาที่แก้ ────────────────────────────────────────────────────────────
 * แท็บในหน้าตั้งค่า (กลุ่มผู้รับ / ประเภทเหตุการณ์ / อุปกรณ์ & key) เป็นคนละ component
 * กัน พอสลับแท็บ React ถอดตัวเก่าออกแล้วสร้างตัวใหม่ ข้อมูลที่โหลดไว้หายไปกับตัวเก่า
 * ตัวใหม่จึงต้องยิง API ใหม่ทุกครั้ง แล้วระหว่างรอก็ยุบเหลือบรรทัดเดียวว่า "กำลังโหลด..."
 *
 * ผลคือทุกครั้งที่กดสลับแท็บ ความสูงของหน้าจะยุบลงแล้วเด้งกลับขึ้นภายในเสี้ยววินาที
 * (API อยู่ในเครื่องเดียวกัน ตอบกลับไม่กี่มิลลิวินาที) — ซึ่งตาอ่านออกมาเป็น "กระพริบ"
 *
 * ── วิธีแก้ ────────────────────────────────────────────────────────────────
 * หน้าที่เคยโหลดสำเร็จแล้วฝากข้อมูลชุดล่าสุดไว้ที่นี่ พอกลับเข้ามาใหม่ก็หยิบไปวาดก่อนเลย
 * ตั้งแต่เฟรมแรก แล้วค่อยยิง API เบื้องหลังไปเงียบๆ ได้ของใหม่มาเมื่อไหร่ค่อยอัปเดตทับ
 * หน้าจึงไม่เคยว่างและไม่เคยยุบ — ไม่มีอะไรให้กระพริบ
 *
 * ── ข้อแลกเปลี่ยน ──────────────────────────────────────────────────────────
 * เฟรมแรกหลังสลับแท็บเป็นข้อมูลของรอบก่อน ถ้ามีคนอื่นแก้ค้างไว้จากอีกเครื่องจะเห็นของเก่า
 * ชั่วครู่ก่อนจะถูกทับด้วยของจริง ระบบนี้ผู้ใช้คนเดียวและแท็บที่เพิ่งออกไปก็เพิ่งโหลดมาเอง
 * ความเสี่ยงจึงต่ำกว่าการกระพริบทุกครั้งที่กดมาก
 *
 * เก็บในตัวแปรธรรมดา ไม่ใช่ localStorage โดยตั้งใจ — ต้องการแค่ให้อยู่รอดข้ามการสลับแท็บ
 * ในรอบการใช้งานเดียว ไม่ใช่ข้ามการรีเฟรชหน้า (รีเฟรชแล้วควรได้ของจริงจากเซิร์ฟเวอร์)
 */

const store = new Map<string, unknown>();

/** คีย์ของแต่ละหน้า — รวมไว้ที่เดียวกันสะกดผิดแล้วแคชไม่ทำงานโดยไม่มีอะไรฟ้อง */
export const SNAP = {
  contacts: 'contacts',
  eventTypes: 'event-types',
  devices: 'devices',
  setupCounts: 'setup-counts',
} as const;

export function readSnapshot<T>(key: string): T | undefined {
  return store.get(key) as T | undefined;
}

export function writeSnapshot<T>(key: string, value: T): void {
  store.set(key, value);
}

/**
 * ทิ้งทั้งหมด — เรียกตอนออกจากระบบ/token หมดอายุ
 * ข้อมูลในนี้เป็นของ session ที่จบไปแล้ว ไม่ควรค้างให้รอบถัดไปเห็น
 */
export function clearSnapshots(): void {
  store.clear();
}
