import { WORLD_H, WORLD_W } from './worldLand';

/** ต้องตรงกับ LAT_MAX / LAT_MIN ใน scripts/gen-world.mjs */
const LAT_MAX = 80;
const LAT_MIN = -56;

function project(lon: number, lat: number): { x: number; y: number } {
  return {
    x: ((lon + 180) / 360) * WORLD_W,
    y: ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * WORLD_H,
  };
}

